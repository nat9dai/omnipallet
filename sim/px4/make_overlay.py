"""Make a PX4 overlay with our airframe for Pegasus, so ~/PX4-Autopilot stays untouched.

    python3 sim/px4/make_overlay.py [--height range|vision]   # writes sim/px4/overlay
"""
import argparse
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "vehicle"))
import design as d  # noqa: E402

PX4 = os.environ.get("PX4_DIR", os.path.expanduser("~/PX4-Autopilot"))
OVERLAY = os.path.join(HERE, "overlay")
AIRFRAME_ID, AIRFRAME_NAME = 22001, "pegasus_stockdrone"

TEMPLATE = """#!/bin/sh
#
# @name Pegasus stock-counting quad (Charpi frame, 7 in props, {mass:.2f} kg)
# @type Quadrotor
# @class Copter
#
# Generated by sim/px4/make_overlay.py from sim/vehicle/design.py. Do not edit by hand.

. ${{R}}etc/init.d/rc.mc_defaults

param set-default CA_AIRFRAME 0
param set-default CA_ROTOR_COUNT 4
{rotors}
param set-default PWM_MAIN_FUNC1 101
param set-default PWM_MAIN_FUNC2 102
param set-default PWM_MAIN_FUNC3 103
param set-default PWM_MAIN_FUNC4 104

# thrust curve: w = {w_idle:.0f} + {w_span:.0f} u rad/s and T = k_T w^2, so T/T_max ~ (1-f) u + f u^2
param set-default THR_MDL_FAC {thr_mdl_fac:.2f}
param set-default MPC_THR_HOVER {hover:.2f}
param set-default MPC_THR_MIN 0.08
param set-default MPC_USE_HTE 1

# rate loop: the tuned Charpi gains (K 0.6 x P 0.10) scaled by its torque-to-inertia ratio over ours
param set-default MC_ROLLRATE_K 1.0
param set-default MC_ROLLRATE_P {rate_p}
param set-default MC_ROLLRATE_I {rate_i}
param set-default MC_ROLLRATE_D {rate_d}
param set-default MC_PITCHRATE_K 1.0
param set-default MC_PITCHRATE_P {rate_p}
param set-default MC_PITCHRATE_I {rate_i}
param set-default MC_PITCHRATE_D {rate_d}
param set-default MC_YAWRATE_P 0.25
param set-default MC_YAWRATE_I 0.1

# position loop: gentle limits for a 2.5 m aisle
param set-default MPC_XY_VEL_MAX 3.0
param set-default MPC_Z_VEL_MAX_UP 1.5
param set-default MPC_Z_VEL_MAX_DN 1.0
param set-default MPC_ACC_HOR 2.0
param set-default MPC_ACC_HOR_MAX 3.0
param set-default MPC_TILTMAX_AIR 25
param set-default MPC_LAND_SPEED 0.5
param set-default MPC_TKO_SPEED 0.8

# GPS-denied: no GPS, no magnetometer, external vision for position, velocity and yaw;
# height from the downward lidar (or from vision with --height vision)
param set-default SYS_HAS_GPS 0
param set-default SYS_HAS_MAG 0
param set-default EKF2_GPS_CTRL 0
param set-default EKF2_MAG_TYPE 5
param set-default EKF2_BARO_CTRL 1
{height}
param set-default EKF2_EV_DELAY {ev_delay}
param set-default EKF2_EVP_NOISE 0.05
param set-default EKF2_EVV_NOISE 0.1
param set-default EKF2_EVA_NOISE 0.05
param set-default EKF2_EV_NOISE_MD 0
param set-default COM_ARM_WO_GPS 1

# no RC in simulation: offboard is the only pilot; land on offboard loss
param set-default COM_RC_IN_MODE 4
param set-default NAV_RCL_ACT 0
param set-default NAV_DLL_ACT 0
param set-default COM_RCL_EXCEPT 4
param set-default COM_OF_LOSS_T 1.0
param set-default COM_OBL_RC_ACT 4
param set-default COM_DISARM_PRFLT 60

# sim time runs slower than wall time when many cameras render: keep PX4 stamps raw
param set-default UXRCE_DDS_SYNCT 0
param set-default SIM_BAT_DRAIN 3600
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ev-delay-ms", type=float, default=0.0, help="EKF2_EV_DELAY (ms)")
    ap.add_argument("--height", choices=["range", "vision"], default="range", help="EKF2 height reference")
    ap.add_argument("--rate-pid", type=float, nargs=3, default=[0.09, 0.12, 0.0015], help="roll/pitch rate P I D")
    args = ap.parse_args()
    romfs = os.path.join(OVERLAY, "ROMFS", "px4fmu_common")
    if os.path.isdir(romfs):
        shutil.rmtree(romfs)
    shutil.copytree(os.path.join(PX4, "ROMFS", "px4fmu_common"), romfs, symlinks=True)
    build = os.path.join(OVERLAY, "build")
    if not os.path.islink(build):
        os.symlink(os.path.join(PX4, "build"), build)
    rotors = []
    for i, ((x, y, _), sdir) in enumerate(zip(d.ROTORS, d.ROT_DIR)):
        # PX4 is FRD: y flips; KM > 0 for CCW rotors
        km = d.KM if sdir < 0 else -d.KM
        rotors.append(f"param set-default CA_ROTOR{i}_PX {x:.3f}\nparam set-default CA_ROTOR{i}_PY {-y:.3f}\n"
                      f"param set-default CA_ROTOR{i}_KM {km:.4f}")
    if args.height == "range":
        # EV gives horizontal position, velocity and yaw (bits 1+4+8); the lidar gives height
        height = (f"param set-default EKF2_EV_CTRL 13\nparam set-default EKF2_HGT_REF 2\n"
                  f"param set-default EKF2_RNG_CTRL 2\nparam set-default EKF2_RNG_POS_Z {-d.RANGE_POS[2]:.3f}\n"
                  f"param set-default EKF2_MIN_RNG 0.01\n"  # keep small: also the floor std dev at take-off
                  f"param set-default EKF2_RNG_NOISE {2 * d.RANGE_SIGMA:.3f}\nparam set-default EKF2_RNG_SFE 0.01")
    else:
        height = "param set-default EKF2_EV_CTRL 15\nparam set-default EKF2_HGT_REF 3\nparam set-default EKF2_RNG_CTRL 0"
    text = TEMPLATE.format(height=height, mass=d.MASS, rotors="\n".join(rotors), w_idle=d.W_IDLE, w_span=d.W_MAX - d.W_IDLE,
                           thr_mdl_fac=d.thr_mdl_fac(), hover=d.hover_thrust_norm(), ev_delay=args.ev_delay_ms,
                           rate_p=args.rate_pid[0], rate_i=args.rate_pid[1], rate_d=args.rate_pid[2])
    path = os.path.join(romfs, "init.d-posix", "airframes", f"{AIRFRAME_ID}_{AIRFRAME_NAME}")
    with open(path, "w") as f:
        f.write(text)
    os.chmod(path, 0o755)
    print("overlay:", OVERLAY)
    print("airframe:", path)
    print(f"Pegasus config: px4_dir={OVERLAY}, px4_vehicle_model={AIRFRAME_NAME}, "
          f"zero_position_armed={d.W_IDLE}, input_scaling={d.W_MAX - d.W_IDLE}")


if __name__ == "__main__":
    main()
